@case
def t09_corrupted_and_invalid_files_show_error_no_crash(pg):
    import tempfile
    fresh(pg)
    d = tempfile.mkdtemp()
    for nm, content in [("bad.pdf", b"not a pdf at all"), ("trunc.pdf", open(os.path.join(SM, "sample_report_01_text.pdf"), "rb").read()[:300]),
                        ("bad.png", b"\x89PNG\r\n\x1a\n" + os.urandom(200))]:
        p = os.path.join(d, nm); open(p, "wb").write(content)
        pg.set_input_files("input[type=file]", p); pg.wait_for_selector("text=/❌/", timeout=30000)
        assert pg.get_by_role("heading", name="Extracted values").count() == 0 and pg.get_by_text("Traceback").count() == 0, nm
        pg.locator('button[aria-label^="Remove"]').first.click() if pg.locator('button[aria-label^="Remove"]').count() else None; pg.wait_for_timeout(500)

