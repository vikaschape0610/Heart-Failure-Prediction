@case
def t14_malicious_text_in_report_is_escaped(pg):
    import tempfile
    from reportlab.pdfgen import canvas
    p = os.path.join(tempfile.mkdtemp(), "x.pdf"); c = canvas.Canvas(p)
    for i, t in enumerate(['Age: 60 <img src=x onerror="window.__xss=1"> years', "Sex: Male", "Ejection Fraction 40 % padding text to exceed threshold"]): c.drawString(72, 700 - 20 * i, t)
    c.drawString(72, 600, "Report body long enough to be treated as a text layer rather than a scan page."); c.save()
    fresh(pg); upload(pg, p); pg.wait_for_timeout(800)
    assert pg.evaluate("window.__xss === undefined") and pg.locator("img[src='x']").count() == 0

with sync_playwright() as p:
    b = p.chromium.launch(); ctx = b.new_context(viewport={"width": 1400, "height": 2300}, color_scheme="dark")
    for t in [t01_manual_mode_unchanged_still_predicts, t02_text_pdf_values_shown_read_only, t03_no_review_checkbox_and_compute_works_directly,
              t04_confirmed_prediction_matches_original_baseline, t05_several_out_of_range_values_red_and_still_computed,
              t06_scanned_pdf_ocr_requires_verification_then_predicts, t07_image_upload_jpg_conversions_flagged,
              t08_incomplete_report_cannot_be_computed_and_nothing_is_guessed, t09_corrupted_and_invalid_files_show_error_no_crash,
              t10_value_below_set_range_marked_red_low, t11_impossible_value_is_never_computed,
              t12_removing_file_clears_review_and_back_to_manual, t13_other_tabs_still_work, t14_malicious_text_in_report_is_escaped]:
        pg = ctx.new_page(); pg.set_default_timeout(20000); t(pg); pg.close()
    b.close()
print("\n===== E2E RESULTS ====="); [print(f"{s}  {n}  {m}") for n, s, m in RES]
